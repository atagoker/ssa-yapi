const root = document.documentElement;
const languageToggle = document.querySelector("#languageToggle");
const themeToggle = document.querySelector("#themeToggle");
const projectTrack = document.querySelector("#projectTrack");
const projectPrev = document.querySelector("#projectPrev");
const projectNext = document.querySelector("#projectNext");

const savedLanguage = "tr";
const savedTheme = "light";

function setLanguage(language) {
  const dictionary = translations[language];
  document.documentElement.lang = language;

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) {
      element.textContent = dictionary[key];
    }
  });

  languageToggle.textContent = language === "tr" ? "EN" : "TR";
  renderReferences(language);
}

function setTheme(theme) {
  root.dataset.theme = theme;
}

function renderReferences(language) {
  projectTrack.innerHTML = references
    .map((item, index) => {
      return `
        <article class="reference-card">
          <div>
            <div class="reference-topline">
              <span>${item.year}</span>
              <span>${item.location}</span>
            </div>
            <h3>${item.title}</h3>
            <p>${item[language]}</p>
          </div>
          <div class="reference-detail">
            <span>${item.client}</span>
          </div>
        </article>
      `;
    })
    .join("");
}

function moveProjectTrack(direction) {
  const card = projectTrack.querySelector(".reference-card");
  if (!card) return;
  const distance = card.getBoundingClientRect().width + 1;
  projectTrack.scrollBy({ left: direction * distance, behavior: "smooth" });
}

setTheme(savedTheme);
setLanguage(savedLanguage);

languageToggle.addEventListener("click", () => {
  const nextLanguage = document.documentElement.lang === "tr" ? "en" : "tr";
  setLanguage(nextLanguage);
});

themeToggle.addEventListener("click", () => {
  const nextTheme = root.dataset.theme === "dark" ? "light" : "dark";
  setTheme(nextTheme);
});

projectPrev.addEventListener("click", () => moveProjectTrack(-1));
projectNext.addEventListener("click", () => moveProjectTrack(1));
